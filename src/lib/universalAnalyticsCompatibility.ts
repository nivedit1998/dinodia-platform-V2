import type { Prisma } from '@prisma/client';
import { Stage1AuthError } from './stage1Auth';
import { hasCurrentAnalyticsContract, type AnalyticsContractAcknowledgement } from './analyticsContractAcknowledgement';

export const UNIVERSAL_ANALYTICS_CONTRACT = 1;
export const UNIVERSAL_ANALYTICS_CATEGORIES = ['SOCKET','TV','BLIND','AC','WASHING_MACHINE'] as const;
export const universalAnalyticsEnabled = () => process.env.DINODIA_UNIVERSAL_ANALYTICS_ENABLED === 'true';
const MAX_ACK_AGE_MS = 15 * 60_000;
type Identity = { id:string; identityGeneration:number };
export async function universalAnalyticsRuntimeAvailable(tx:Prisma.TransactionClient,hubInstallationId:string) {
  if (!universalAnalyticsEnabled()) return false;
  const rows = await tx.$queryRaw<Array<{proof:unknown;homeId:string;hubId:string;revision:number;identityId:string;generation:number}>>`
    SELECT h."analyticsContractAck" AS proof,home.id AS "homeId",h.id AS "hubId",h."cloudConfigurationRevision" AS revision,
      i.id AS "identityId",i."identityGeneration" AS generation
    FROM "HubInstallation" h JOIN "HubManufacturingIdentity" i ON i.id=h."manufacturingIdentityId" AND i.status='ACTIVE'
    JOIN "Home" home ON home.id=h."homeId" AND home."activeHubInstallationId"=h.id AND home.lifecycle='ACTIVE'
    WHERE h.id=${hubInstallationId}::uuid AND h.state='ACTIVE'`;
  const row=rows[0],p=row?.proof as Record<string,unknown>|null;
  const age=Date.now()-Date.parse(String(p?.receivedAt));
  return Boolean(p && p.homeId===row.homeId && p.hubInstallationId===row.hubId
    && Number.isSafeInteger(p.appliedCloudRevision) && Number(p.appliedCloudRevision)>=0 && Number(p.appliedCloudRevision)<=row.revision
    && p.manufacturingIdentityId===row.identityId && p.identityGeneration===row.generation
    && p.analyticsContractVersion===UNIVERSAL_ANALYTICS_CONTRACT && p.invalidatedAt===null && age>=0 && age<=MAX_ACK_AGE_MS);
}

/** Fresh token-state requests are generated by the running process, outside
 * the durable analytics outbox. Binding the declaration to its signed request
 * nonce prevents replaying an old declaration with a newly signed request.
 * This is an authenticated capability declaration, not binary attestation. */
export async function recordUniversalAnalyticsCompatibility(tx:Prisma.TransactionClient, input:{
  homeId:string; hubInstallationId:string; identity:Identity; declaration:unknown;
  requestNonce:string; now:Date;
}) {
  await tx.$queryRaw`SELECT id FROM "Home" WHERE id=${input.homeId}::uuid FOR UPDATE`;
  const rows = await tx.$queryRaw<Array<{homeId:string;state:string;manufacturingIdentityId:string;cloudConfigurationRevision:number;acknowledgedCloudRevision:number}>>`
    SELECT "homeId",state,"manufacturingIdentityId","cloudConfigurationRevision","acknowledgedCloudRevision" FROM "HubInstallation"
    WHERE id=${input.hubInstallationId}::uuid FOR UPDATE`;
  const current = rows[0];
  const active = await tx.home.findFirst({where:{id:input.homeId,lifecycle:'ACTIVE',activeHubInstallationId:input.hubInstallationId},select:{id:true}});
  const identity = await tx.hubManufacturingIdentity.findFirst({where:{id:input.identity.id,identityGeneration:input.identity.identityGeneration,status:'ACTIVE'},select:{id:true}});
  const p = input.declaration && typeof input.declaration === 'object' && !Array.isArray(input.declaration) ? input.declaration as Record<string,unknown> : null;
  const supported = current?.homeId === input.homeId && current.state === 'ACTIVE' && current.manufacturingIdentityId === input.identity.id && active && identity
    && p && p.contractVersion === UNIVERSAL_ANALYTICS_CONTRACT && p.analyticsPolicyVersion === 4
    && p.requestNonce === input.requestNonce && typeof p.runtimeSessionId === 'string' && /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(p.runtimeSessionId)
    && Number.isSafeInteger(p.appliedCloudRevision) && p.appliedCloudRevision === current.cloudConfigurationRevision
    && p.appliedCloudRevision === current.acknowledgedCloudRevision;
  const proof = supported ? {homeId:input.homeId,hubInstallationId:input.hubInstallationId,
    manufacturingIdentityId:input.identity.id,identityGeneration:input.identity.identityGeneration,
    analyticsContractVersion:UNIVERSAL_ANALYTICS_CONTRACT,appliedCloudRevision:p!.appliedCloudRevision,
    receivedAt:input.now.toISOString(),invalidatedAt:null,runtimeSessionId:p!.runtimeSessionId} : null;
  await tx.$executeRaw`UPDATE "HubInstallation" SET "analyticsContractAck"=${JSON.stringify(proof)}::jsonb WHERE id=${input.hubInstallationId}::uuid`;
}

/** Called while holding the Home lock, before any category/epoch mutation. */
export async function requireUniversalAnalyticsCompatibility(tx:Prisma.TransactionClient, input:{homeId:string;hubInstallationId:string;identity:Identity;now?:Date}) {
  if (!universalAnalyticsEnabled()) throw new Stage1AuthError(409,'analytics_contract_unavailable','This analytics category is not enabled on the Home yet');
  await tx.$queryRaw`SELECT id FROM "Home" WHERE id=${input.homeId}::uuid FOR UPDATE`;
  const rows = await tx.$queryRaw<Array<{homeId:string;state:string;manufacturingIdentityId:string;cloudConfigurationRevision:number;analyticsWriterEnabled:boolean;analyticsContractAck:unknown}>>`
    SELECT "homeId",state,"manufacturingIdentityId","cloudConfigurationRevision","analyticsWriterEnabled","analyticsContractAck" FROM "HubInstallation"
    WHERE id=${input.hubInstallationId}::uuid FOR UPDATE`;
  const current = rows[0];
  const active = await tx.home.findFirst({where:{id:input.homeId,lifecycle:'ACTIVE',activeHubInstallationId:input.hubInstallationId},select:{id:true}});
  const identity = await tx.hubManufacturingIdentity.findFirst({where:{id:input.identity.id,identityGeneration:input.identity.identityGeneration,status:'ACTIVE'},select:{id:true}});
  const raw = current?.analyticsContractAck as Record<string,unknown>|null;
  const proof = raw ? {...raw,receivedAt:new Date(String(raw.receivedAt)),invalidatedAt:raw.invalidatedAt === null ? null : new Date(String(raw.invalidatedAt))} as AnalyticsContractAcknowledgement : null;
  if (!current?.analyticsWriterEnabled || !hasCurrentAnalyticsContract(proof,{
    homeId:input.homeId,hubInstallationId:input.hubInstallationId,manufacturingIdentityId:current?.manufacturingIdentityId || '',
    identityGeneration:input.identity.identityGeneration,identityActive:Boolean(identity),installationActive:Boolean(active)&&current?.state==='ACTIVE',currentCloudRevision:current?.cloudConfigurationRevision || 0,
  },UNIVERSAL_ANALYTICS_CONTRACT,input.now || new Date(),MAX_ACK_AGE_MS))
    throw new Stage1AuthError(409,'analytics_contract_unavailable','The active Home must acknowledge compatible analytics software before this category can be assigned');
}
